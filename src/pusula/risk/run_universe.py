"""Compute risk reports for the whole universe on one date and assign risk levels.

    uv run python -m pusula.risk.run_universe                    # latest session, all bases
    uv run python -m pusula.risk.run_universe --as-of 2025-11-03  # e.g. SELECTION_DATE

* Reports are stored in DuckDB (``risk_reports``) and in ``results/risk_universe/<timestamp>/``
  with a copy of ``settings.yaml``, timings and exclusions.
* The relative risk level (D-037) is computed in nominal TRY and attached to the reports of all
  bases.
* Names with fewer than ``min_history`` returns get no report (D-031). When the date is
  SELECTION_DATE, they are listed in ``docs/e4_eligibility.md``: E4's default subset may only use
  names with a valid report (D-038).
"""

from __future__ import annotations

import argparse
import logging
import shutil
import time
from datetime import UTC, date, datetime

import pandas as pd

from pusula.config import CONFIG_DIR, ROOT_DIR, get_settings
from pusula.data.store import Store
from pusula.features.returns import BASES
from pusula.logging_setup import setup_logging
from pusula.risk.engine import InsufficientHistoryError, compute_risk_report, load_inputs
from pusula.risk.level import assign_risk_levels
from pusula.risk.models import ModelFitError
from pusula.universe.members import universe_members

log = logging.getLogger(__name__)


def run(as_of: date, bases=BASES, store: Store | None = None) -> pd.DataFrame:
    s = get_settings()
    store = store or Store(s.paths.db_path, s.paths.raw_dir)
    inp = load_inputs(store, as_of)
    as_of = inp.sessions.max().date() if inp.sessions.max().date() < as_of else as_of
    inp.as_of = as_of
    members = universe_members(as_of)
    uniq = members.drop_duplicates("symbol")
    reports, rows, excluded = {}, [], []
    for sym in uniq["symbol"]:
        for basis in bases:
            try:
                rep = compute_risk_report(inp, sym, basis, s.risk, s.project.random_seed)
            except (InsufficientHistoryError, ModelFitError) as exc:
                if basis == "TRY":
                    excluded.append({"symbol": sym, "reason": str(exc)})
                    log.warning("%s", exc)
                break
            reports[(sym, basis)] = rep
            rows.append({"symbol": sym, "basis": basis, "vol_ann": rep.vol_ann_realized,
                         "cvar99_1d": rep.horizon_1d.cvar99, "selected_model": rep.selected_model,
                         "seconds": rep.seconds_total})  # fmt: skip
    summary = pd.DataFrame(rows)
    if summary.empty:
        raise RuntimeError("No risk report could be computed")

    lv = assign_risk_levels(
        summary[summary["basis"] == "TRY"].rename(columns={"symbol": "ticker"}),
        s.risk.risk_level_cutoffs,
    ).set_index("ticker")
    out_rows = []
    run_at = datetime.now(UTC).replace(tzinfo=None)
    for (sym, basis), rep in reports.items():
        rep.risk_level = lv.loc[sym, "risk_level"]
        rep.risk_score = float(lv.loc[sym, "risk_score"])
        for g in members[members["symbol"] == sym].itertuples():
            out_rows.append({
                "as_of": as_of, "ticker": sym, "basis": basis, "universe": g.universe,
                "sub_sector": g.sub_sector, "in_bist30": bool(g.in_bist30),
                "risk_level": rep.risk_level, "risk_score": rep.risk_score,
                "vol_ann": rep.vol_ann_realized, "cvar99_1d": rep.horizon_1d.cvar99,
                "selected_model": rep.selected_model, "payload": rep.model_dump_json(),
                "run_at": run_at,
            })  # fmt: skip
    table = pd.DataFrame(out_rows)
    # one row per (as_of, ticker, basis): overlap names keep the Energy label + in_bist30 flag
    table = table.sort_values("universe").drop_duplicates(["as_of", "ticker", "basis"], keep="last")
    store.replace_rows("risk_reports", table, "as_of = ?", [as_of])

    out = s.paths.results_dir / "risk_universe" / f"{as_of:%Y%m%d}_{run_at:%Y%m%d_%H%M%S}"
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(CONFIG_DIR / "settings.yaml", out / "settings.yaml")
    table.drop(columns=["payload"]).to_csv(out / "summary.csv", index=False)
    summary.to_csv(out / "timings.csv", index=False)
    exc = pd.DataFrame(excluded, columns=["symbol", "reason"])
    exc.to_csv(out / "exclusions.csv", index=False)
    if as_of == s.project.selection_date:
        _write_e4_eligibility(as_of, members, exc)
    log.info("Risk run %s: %d reports, %d excluded, %.1fs total, max %.2fs per report -> %s",
             as_of, len(reports), len(exc), summary["seconds"].sum(), summary["seconds"].max(),
             out)  # fmt: skip
    return table


def _write_e4_eligibility(as_of: date, members: pd.DataFrame, exc: pd.DataFrame) -> None:
    lines = [
        "# E4 eligibility at SELECTION_DATE",
        "",
        f"Generated by `python -m pusula.risk.run_universe --as-of {as_of}` (D-038).",
        "E4's default subset may only use names with a valid risk report at this date.",
        "",
    ]
    if exc.empty:
        lines.append("All universe names have a valid report.")
    else:
        e = exc.merge(members[["symbol", "universe"]], on="symbol", how="left")
        lines += ["## Excluded", "", e.to_markdown(index=False)]
    (ROOT_DIR / "docs" / "e4_eligibility.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--as-of", type=date.fromisoformat, default=None)
    p.add_argument("--basis", nargs="+", choices=list(BASES), default=list(BASES))
    a = p.parse_args(argv)
    setup_logging()
    t = time.perf_counter()
    table = run(a.as_of or date.today(), tuple(a.basis))
    print(table[table["basis"] == "TRY"][["ticker", "universe", "risk_level", "risk_score",
          "vol_ann", "cvar99_1d", "selected_model"]].to_string(index=False))  # fmt: skip
    print(f"Done in {time.perf_counter() - t:.1f}s")


if __name__ == "__main__":
    main()
